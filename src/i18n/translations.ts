export const translations: Record<Language, Record<TranslationKey, string>> = { en: english, ar: arabic }

type LanguageStorageReader = Pick<Storage, 'getItem'>
type LanguageStorageWriter = Pick<Storage, 'setItem'>

export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'ar'
}

export function readLanguagePreference(storage: LanguageStorageReader | null): Language {
  if (!storage) return 'en'
  try {
    const storedLanguage = storage.getItem(languagePreferenceKey)
    return isLanguage(storedLanguage) ? storedLanguage : 'en'
  } catch {
    return 'en'
  }
}

export function writeLanguagePreference(language: Language, storage: LanguageStorageWriter | null) {
  if (!storage) return false
  try {
    storage.setItem(languagePreferenceKey, language)
    return true
  } catch {
    return false
  }
}

export function translate(language: Language, key: TranslationKey, variables: TranslationVariables = {}) {
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{{${name}}}`, String(value)),
    translations[language][key],
  )
}

export function translateMessage(language: Language, message: TranslationMessage) {
  return translate(language, message.key, message.variables)
}

export function getEnglishTranslation(key: TranslationKey, variables?: TranslationVariables) {
  return translate('en', key, variables)
}
